#!/usr/bin/env bash
# Pemeriksaan sebelum commit/pengumpulan:
# - tidak ada artefak agen AI atau konfigurasi editor pribadi,
# - tidak ada API key/private key yang tidak sengaja tersimpan,
# - frontend tidak memanggil CDN eksternal saat runtime,
# - file wajib tersedia.
set -uo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

problems=0
warnings=0

fail() {
  echo "FAIL  $*"
  problems=$((problems + 1))
}

warn() {
  echo "WARN  $*"
  warnings=$((warnings + 1))
}

ok() {
  echo "OK    $*"
}

echo "NORA repo hygiene check"
echo "Root: $ROOT"
echo

# ---------------------------------------------------------------------------
# 1. Artefak agen/editor yang tidak boleh ikut repo
# ---------------------------------------------------------------------------
for path in \
  AGENTS.md CLAUDE.md GEMINI.md \
  .cursorrules .windsurfrules \
  .cursor .claude .opencode .codex .continue .aider .copilot \
  copilot-instructions.md .github/copilot-instructions.md \
  mcp.json .mcp.json skills plugins; do
  if [ -e "$path" ]; then
    fail "artefak terlarang ditemukan: $path"
  fi
done

# Pola file sementara/plan/session yang sering ditinggalkan agen.
while IFS= read -r leftover; do
  [ -n "$leftover" ] && fail "file sementara agen ditemukan: $leftover"
done < <(find . -maxdepth 2 -type f \
  \( -name '*plan*.md' -o -name '*session*.md' -o -name '.aider*' \) \
  -not -path './.git/*' -not -path './data/*' 2>/dev/null)

if [ "$problems" -eq 0 ]; then
  ok "tidak ada artefak agen/editor"
fi

# ---------------------------------------------------------------------------
# 2. Kebocoran rahasia
# ---------------------------------------------------------------------------
EXCLUDES=(
  --exclude-dir=.git
  --exclude-dir=data
  --exclude-dir=.venv
  --exclude-dir=venv
  --exclude-dir=node_modules
  --exclude-dir=__pycache__
  --exclude-dir=.pytest_cache
  --exclude-dir=vendor
  --exclude='*.pdf'
  --exclude='*.woff2'
  --exclude='*.db'
)

SECRET_PATTERN='(sk-or-v1-[A-Za-z0-9]{20,}|sk-ant-[A-Za-z0-9_-]{20,}|sk-proj-[A-Za-z0-9_-]{20,}|AIza[0-9A-Za-z_-]{30,}|-----BEGIN (RSA|OPENSSH|EC|DSA) PRIVATE KEY-----)'
if grep -rInE "${EXCLUDES[@]}" "$SECRET_PATTERN" . 2>/dev/null; then
  fail "pola rahasia ditemukan di atas"
else
  ok "tidak ada API key/private key yang terlihat"
fi

if [ -f .env ]; then
  warn ".env ada di working tree lokal (pastikan tidak pernah di-commit)"
fi

# ---------------------------------------------------------------------------
# 3. Tidak ada CDN eksternal di runtime frontend
# ---------------------------------------------------------------------------
CDN_PATTERN='https?://(cdn\.tailwindcss\.com|cdn\.jsdelivr\.net|unpkg\.com|cdnjs\.cloudflare\.com|fonts\.googleapis\.com|fonts\.gstatic\.com|esm\.sh)'
if grep -nE "$CDN_PATTERN" frontend/index.html frontend/vendor/fonts/inter.css 2>/dev/null; then
  fail "referensi CDN eksternal ditemukan di frontend"
else
  ok "frontend memakai aset lokal (tanpa CDN)"
fi

# ---------------------------------------------------------------------------
# 4. Tidak ada atribusi agen AI
# ---------------------------------------------------------------------------
ATTRIBUTION_PATTERN='(Generated by (AI|ChatGPT|Claude|Copilot)|Co-authored-by:.*(Claude|GPT|Copilot)|As an AI language model)'
if grep -rInE "${EXCLUDES[@]}" --exclude='check_repo_hygiene.sh' "$ATTRIBUTION_PATTERN" . 2>/dev/null; then
  fail "teks atribusi agen AI ditemukan"
else
  ok "tidak ada atribusi agen AI"
fi

# ---------------------------------------------------------------------------
# 5. File wajib
# ---------------------------------------------------------------------------
for path in \
  README.md .env.example .gitignore Dockerfile docker-compose.yml \
  backend/requirements.txt backend/app/main.py \
  frontend/index.html frontend/vendor/three.min.js \
  docs/ARCHITECTURE.md docs/API.md docs/AI.md docs/PRIVACY.md \
  docs/DEPLOY.md docs/DEMO_SCRIPT.md docs/ATTRIBUTIONS.md; do
  if [ -f "$path" ]; then
    ok "file wajib: $path"
  else
    fail "file wajib hilang: $path"
  fi
done

# ---------------------------------------------------------------------------
# 6. Data runtime tidak boleh menjadi bagian pengiriman
# ---------------------------------------------------------------------------
if [ -d data ] && find data -mindepth 1 -maxdepth 1 -print -quit 2>/dev/null | grep -q .; then
  warn "folder data/ berisi data runtime; folder ini diabaikan Git tetapi jangan di-zip manual"
fi

echo
if [ "$problems" -gt 0 ]; then
  echo "HASIL: $problems masalah, $warnings peringatan"
  exit 1
fi

echo "HASIL: bersih ($warnings peringatan)"
